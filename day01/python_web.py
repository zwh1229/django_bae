'''
三种不同的框架
django
采用了MVT的软件设计模式，即模型，视图，模板,在MVC上衍生出来的
MVC
M model 数据模型操作数据库的
V view 视图 里面的代码用于展示给客户端页面效果
C Controller 控制器 是一个类或者函数  代码就是用于项目功能逻辑的，一般用于调用模型来获取数据

MVT
M model 也是和数据库做交互
V view 与MVC中的c功能相同，接收请求，处理业务逻辑
T template 与MVC中的v功能相同，负责封装构造返回html

Django —— “大而全的框架”
核心理念：开箱即用，一站式解决方案。
自带 ORM（操作数据库不用写 SQL，直接 Python 类）。
自带模板引擎（生成 HTML）。
自带后台管理（几行代码就有后台可用）。
自带用户认证、权限系统、session。
强调 约定优于配置：很多功能都有固定写法，你按套路来就行。
👉 本质：Django 就像一辆“大巴车”，买了就有司机、座位、空调、导航，适合做 大型网站/企业应用。
缺点是：太重，不灵活，学起来有门槛。



flask
“小而灵的框架”
核心理念：极简核心 + 自由扩展。
只有最基础的功能：路由、请求、响应。
ORM？模板？用户认证？日志？👉 你自己决定要不要装插件。
学习成本低，写一个 demo 非常快。
灵活，但也容易导致项目越写越乱（因为没有统一规范）。
👉 本质：Flask 就像一辆“自行车”，轻巧，爱怎么玩怎么玩，适合 小项目、快速原型、API 服务。
缺点是：项目一旦大了，维护难度高，需要自己定规范。

fastapi
核心理念：为 API 而生，主打性能和数据安全。
内置 Pydantic：请求参数自动校验（类型、格式、范围），减少手写校验逻辑。
自动生成文档（Swagger UI、Redoc），写好接口函数就能调试。
天然支持 异步 async/await，高并发性能强。
更关注 JSON API / 微服务，而不是渲染网页。
👉 本质：FastAPI 就像一辆“新能源电动车”，科技感强，性能高，适合 现代微服务、AI接口、前后端分离项目。
缺点是：生态还没 Django 完善，很多东西需要拼第三方库。


框架定位：
Flask —— 简单灵活，轻量原型工具。
FastAPI —— 现代化 API 框架，天生异步，高性能。

编程模式：
Flask —— 同步为主，要异步得加插件。
FastAPI —— 原生支持 async/await，高并发不怕阻塞。

数据校验：
Flask —— 自己写逻辑或用第三方库。
FastAPI —— 内置 Pydantic，自动校验参数和类型。

接口文档：
Flask —— 没有自动文档，需要额外写。
FastAPI —— 自动生成 Swagger/Redoc，接口即文档。

性能：
Flask —— 普通 Python Web 性能，适合中小型场景。
FastAPI —— 接近 Node.js/Go 的速度，适合大规模 API 服务。

一句话记：Flask 就像“自由的瑞士军刀”，能干很多事但要你自己拼；FastAPI 是“现代自动化工厂”，自带高效生产线。
'''